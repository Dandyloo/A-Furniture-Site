const originalRenderArticles = renderArticles;
renderArticles = function(articles) {
  originalRenderArticles(articles);
  setTimeout(() => {
    document.querySelectorAll('.news-card').forEach(el => {
      observer.observe(el);
    });
  }, 100);
};

// CHECK FOR ARTICLE ID IN URL (for direct linking)
function checkURLForArticle() {
  const urlParams = new URLSearchParams(window.location.search);
  const articleId = urlParams.get('article');
  
  if (articleId) {
    const article = articlesDatabase.find(a => a.id === parseInt(articleId));
    if (article) {
      // Wait a bit for page to load, then open modal
      setTimeout(() => {
        openModal(article);
      }, 500);
    }
  }
}

