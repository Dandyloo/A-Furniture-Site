// FORMAT DATE
function formatDate(dateString) {
  const date = new Date(dateString);
  const options = { year: 'numeric', month: 'long', day: 'numeric' };
  return date.toLocaleDateString('en-US', options);
}

// SORT ARTICLES
function sortArticles(order) {
  if (order === 'newest') {
    currentArticles.sort((a, b) => new Date(b.date) - new Date(a.date));
  } else if (order === 'oldest') {
    currentArticles.sort((a, b) => new Date(a.date) - new Date(b.date));
  }
}

// FILTER ARTICLES
function filterArticles() {
  const searchTerm = searchInput.value.toLowerCase().trim();
  const sortOrder = sortFilter.value;

  let filtered = [...articlesDatabase];

  // Filter by search
  if (searchTerm) {
    filtered = filtered.filter(article =>
      article.title.toLowerCase().includes(searchTerm) ||
      article.excerpt.toLowerCase().includes(searchTerm) ||
      article.content.toLowerCase().includes(searchTerm)
    );
  }

  currentArticles = filtered;
  sortArticles(sortOrder);
  renderArticles(currentArticles);
}

// OPEN MODAL
function openModal(article) {
  currentArticle = article;

  // Set content
  modalDate.textContent = formatDate(article.date);
  modalTitle.textContent = article.title;
  modalImage.src = article.image;
  modalImage.alt = article.title;
  modalContent.innerHTML = article.content;

  // Add gallery if exists
  if (article.gallery && article.gallery.length > 0) {
    const galleryHTML = createGallery(article.gallery);
    modalContent.innerHTML += galleryHTML;
    
    // Attach gallery click handlers after adding to DOM
    setTimeout(() => {
      attachGalleryHandlers();
    }, 0);
  }

  // Setup share buttons
  setupShareButtons(article);

  // Show modal
  articleModal.classList.add('active');
  document.body.style.overflow = 'hidden';

  // Scroll to top of modal
  document.querySelector('.modal-content').scrollTop = 0;
}

// CREATE GALLERY HTML
function createGallery(images) {
  const galleryItems = images.map((img, index) => `
    <div class="gallery-item" data-index="${index}">
      <img src="${img}" alt="Gallery image ${index + 1}" loading="lazy" />
    </div>
  `).join('');

  return `
    <div class="article-gallery">
      <h3>Event Gallery</h3>
      <div class="gallery-grid">
        ${galleryItems}
      </div>
    </div>
  `;
}

// ATTACH GALLERY CLICK HANDLERS
function attachGalleryHandlers() {
  const galleryItems = document.querySelectorAll('.gallery-item');
  galleryItems.forEach(item => {
    item.addEventListener('click', () => {
      const index = parseInt(item.dataset.index);
      openLightbox(currentArticle.gallery, index);
    });
  });
}

